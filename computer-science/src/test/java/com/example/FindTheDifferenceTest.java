package com.example;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.util.HashMap;
import java.util.HashSet;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

public class FindTheDifferenceTest {

  /*
You are given two strings s and t.

String t is generated by random shuffling string s and then add one more letter at a random position.

Return the letter that was added to t.



Example 1:

Input: s = "abcd", t = "abcde"
Output: "e"
Explanation: 'e' is the letter that was added.
Example 2:

Input: s = "", t = "y"
Output: "y"


Constraints:

0 <= s.length <= 1000
t.length == s.length + 1
s and t consist of lowercase English letters.
   */

  @ParameterizedTest
  @CsvSource({
      "abcd, abcde, e",
      ", y, y"
  })
  public void findTheDifferenceTest(String word1, String word2, String result){
    assertEquals(result.charAt(0), findTheDifference(word1 == null ? "": word1, word2));
  }

  public Character findTheDifference(String word1, String word2) {
    HashMap<Character, Integer> counter = new HashMap<>(word2.length());

    for (int i = 0; i < word1.length(); i++) {
      char c1 = word2.charAt(i);
      char c2 = word1.charAt(i);

      if (c1 == c2) {
        continue;
      }

      counter.compute(c1, (k,v)-> (v==null) ? 1 : v + 1);
      counter.compute(c2, (k,v)-> (v==null) ? -1: v-1);
    }

    counter.compute(word2.charAt(word2.length() - 1), (k,v)-> (v==null) ? 1 : v + 1);

    for (var es : counter.entrySet()){
      if (es.getValue() == 1) {
        return es.getKey();
      }
    }
   return null;
  }
}
